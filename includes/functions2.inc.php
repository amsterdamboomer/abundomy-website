/**
 * Records a book download in both detailed logs and aggregated totals.
 */
function recordDownload($lang, $conn) {
    // 1. Sanitize the language code (lowercase, letters only, 2 chars)
    $lang = substr(preg_replace("/[^a-z]/", "", strtolower($lang)), 0, 2);
    
    // 2. Insert into downloadLog (Audit Trail)
    $stmt = $conn->prepare("INSERT INTO downloadLog (datetime, language) VALUES (NOW(), ?)");
    if ($stmt) {
        $stmt->bind_param("s", $lang);
        $stmt->execute();
        $stmt->close();
    }

    // 3. Update the aggregated downloads table
    // Whitelist to prevent SQL injection via dynamic column names
    $allowedLangs = [
        'ah','ar','am','az','by','be','bo','bg','ca','ch','cz','se','da','de','en','es',
        'fp','fr','gu','ir','gr','ha','he','hi','cr','ig','in','ic','it','ja','ka','kh','ki',
        'sh','co','ko','kg','la','lv','lt','hu','mg','ma','ml','mo','bu','ne','np','no',
        'or','pa','pe','po','ps','pt','pu','ro','ru','zi','al','sl','sk','so','fi','sw','ta','th',
        'vi','tu','ur','yo'
    ];
    
    if (in_array($lang, $allowedLangs)) {
        // Use backticks for the dynamic column name
        $sql = "UPDATE downloads SET total = total + 1, `$lang` = `$lang` + 1 WHERE did = 1";
        mysqli_query($conn, $sql);
    }
}

/**
 * AJAX Listener: Intercepts the background fetch request from index.php
 */
if (isset($_POST['action']) && $_POST['action'] === 'track_download' && isset($_POST['lang'])) {
    // Ensure the database connection is available
    if (!isset($conn)) {
        require_once "includes/dbh.inc.php";
    }
    
    recordDownload($_POST['lang'], $conn);
    
    // Stop script execution so the background request doesn't render HTML
    exit(); 
}


function detectBestLanguage($supportedLangs, $default = 'en') {
    if (!isset($_SERVER['HTTP_ACCEPT_LANGUAGE'])) return $default;
    preg_match_all('/([a-z]{1,8}(-[a-z]{1,8})?)\s*(;\s*q\s*=\s*(1|0\.[0-9]+))?/i', $_SERVER['HTTP_ACCEPT_LANGUAGE'], $matches);
    foreach ($matches[1] as $lang) {
        $clean = strtolower(substr($lang, 0, 2));
        if (in_array($clean, $supportedLangs)) return $clean;
    }
    return $default;
}

